import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import {
  extractFeaturesForVersion,
  hasVersionHeading,
} from "./lib/changelog-features.mjs";

const manifest = JSON.parse(readFileSync("manifest.json", "utf8"));
const changelog = readFileSync("CHANGELOG.md", "utf8");

if (!hasVersionHeading(changelog, manifest.version)) {
  console.warn(
    `[generate-whats-new-content] No "## ${manifest.version}" heading found in CHANGELOG.md — ` +
      `the What's New popup will be empty for this build. If this is a release build, check ` +
      `whether CHANGELOG.md's "## Unreleased" heading still needs renaming to "## ${manifest.version}".`,
  );
}

const features = extractFeaturesForVersion(changelog, manifest.version) ?? [];

const output = `/*
 * AUTO-GENERATED by scripts/generate-whats-new-content.mjs — do not edit by hand.
 * Regenerated as part of \`npm run build\` from CHANGELOG.md's current-version
 * Features section. See docs/adr/0008-embed-release-summaries-at-build-time.md.
 */
export const WHATS_NEW_VERSION = ${JSON.stringify(manifest.version)};
export const WHATS_NEW_FEATURES: string[] = ${JSON.stringify(features, null, 2)};
`;

mkdirSync("src/generated", { recursive: true });
writeFileSync("src/generated/whats-new-content.ts", output);
console.log(
  `Generated src/generated/whats-new-content.ts for v${manifest.version} (${features.length} feature${features.length === 1 ? "" : "s"}).`,
);
