import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import {
  extractFeaturesForVersion,
  hasVersionHeading,
} from "./lib/changelog-features.mjs";

const OUTPUT_PATH = "src/generated/whats-new-content.ts";

const manifest = JSON.parse(readFileSync("manifest.json", "utf8"));
const changelog = readFileSync("CHANGELOG.md", "utf8");

if (!hasVersionHeading(changelog, manifest.version)) {
  console.warn(
    `[generate-whats-new-content] No "## ${manifest.version}" heading found in CHANGELOG.md — ` +
      `the What's New popup will be empty for this build. If this is a release build, check ` +
      `whether CHANGELOG.md's "## Unreleased" heading still needs renaming to "## ${manifest.version}".`,
  );
}

const features = extractFeaturesForVersion(changelog, manifest.version) ?? [];

const output = `/*
 * AUTO-GENERATED by scripts/generate-whats-new-content.mjs — do not edit by hand.
 * Regenerated manually as a release-prep step, right after renaming
 * CHANGELOG.md's "## Unreleased" heading to the real version, and committed
 * alongside that rename. Not run by \`npm run build\`/\`npm run dev\` — see
 * docs/adr/0008-embed-release-summaries-at-build-time.md for why coupling
 * this to the general build pipeline caused unwanted churn on every build.
 */
export const WHATS_NEW_VERSION = ${JSON.stringify(manifest.version)};
export const WHATS_NEW_FEATURES: string[] = ${JSON.stringify(features, null, 2)};
`;

if (existsSync(OUTPUT_PATH) && readFileSync(OUTPUT_PATH, "utf8") === output) {
  console.log(`${OUTPUT_PATH} is already up to date for v${manifest.version} — nothing to write.`);
} else {
  mkdirSync("src/generated", { recursive: true });
  writeFileSync(OUTPUT_PATH, output);
  console.log(
    `Generated ${OUTPUT_PATH} for v${manifest.version} (${features.length} feature${features.length === 1 ? "" : "s"}).`,
  );
}
